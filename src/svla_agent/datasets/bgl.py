"""Loghub **BGL** (BlueGene/L supercomputer) adapter.

BGL is a 4.7 M-line, 215-day RAS log with a per-line alert label - the first
field is ``-`` for normal lines or an alert tag such as ``KERNDTLB`` /
``KERNSTOR`` / ``APPSEV``. Nothing in it was generated by us, which makes it an
honest out-of-distribution test of the pipeline's *structure*: parsing,
anomaly detection at window level, clustering and retrieval. The silicon root-
cause catalogue does not apply and is expected to score zero.

The adapter streams the raw file and writes fixed time windows as native runs:

    run_<idx>.bgl.log      [hh:mm:ss.mmm] <COMPONENT>: <LEVEL>: <content> | node=... type=...
    run_<idx>.label.json   anomalous = any alert line in the window;
                           failure_types / root_cause_id = the alert tags

Line format (space separated, content may itself contain spaces):
    label epoch date node timestamp node type component level content...
"""

from __future__ import annotations

import json
import re
import zipfile
from collections import Counter
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from urllib.request import urlretrieve

ZENODO_URL = "https://zenodo.org/api/records/8196385/files/BGL.zip/content"

_LINE_RE = re.compile(
    r"^(?P<label>\S+) (?P<epoch>\d+) (?P<date>\S+) (?P<node>\S+) (?P<ts>\S+) (?P<node2>\S+) "
    r"(?P<type>\S+) (?P<component>\S+) (?P<level>\S+)(?: (?P<content>.*))?$"
)

_LEVELS = {
    "INFO": "INFO",
    "WARNING": "WARN",
    "SEVERE": "ERROR",
    "ERROR": "ERROR",
    "FAILURE": "ERROR",
    "FATAL": "FATAL",
}


@dataclass(frozen=True)
class BGLRecord:
    label: str
    epoch: int
    node: str
    msg_type: str
    component: str
    level: str
    content: str

    @property
    def is_alert(self) -> bool:
        return self.label != "-"


def parse_bgl_line(line: str) -> BGLRecord | None:
    m = _LINE_RE.match(line.rstrip("\n"))
    if not m:
        return None
    return BGLRecord(
        label=m["label"],
        epoch=int(m["epoch"]),
        node=m["node"],
        msg_type=m["type"],
        component=m["component"],
        level=_LEVELS.get(m["level"].upper(), "INFO"),
        content=(m["content"] or "").strip(),
    )


def _fmt_ts(ms: int) -> str:
    s, ms = divmod(ms, 1000)
    h, s = divmod(s, 3600)
    m, s = divmod(s, 60)
    return f"[{h % 24:02d}:{m:02d}:{s:02d}.{ms:03d}]"


def download(dest_dir: str | Path) -> Path:
    """Fetch BGL.zip from Zenodo and unpack BGL.log into ``dest_dir``."""
    dest = Path(dest_dir)
    dest.mkdir(parents=True, exist_ok=True)
    log = dest / "BGL.log"
    if log.exists():
        return log
    zip_path = dest / "BGL.zip"
    if not zip_path.exists():
        urlretrieve(ZENODO_URL, zip_path)
    with zipfile.ZipFile(zip_path) as zf:
        zf.extract("BGL.log", dest)
    return log


def convert(
    src: str | Path,
    out_logs: str | Path,
    out_labels: str | Path,
    *,
    window_s: int = 1800,
    limit: int | None = None,
    min_lines: int = 20,
) -> dict:
    """Split the BGL stream into time windows and write native runs + labels.

    Returns a summary dict (windows written, lines, alert lines, unparsed lines).
    """
    out_logs = Path(out_logs)
    out_labels = Path(out_labels)
    out_logs.mkdir(parents=True, exist_ok=True)
    out_labels.mkdir(parents=True, exist_ok=True)

    stats: Counter[str] = Counter(
        dict.fromkeys(
            (
                "lines",
                "alert_lines",
                "unparsed_lines",
                "windows",
                "anomalous_windows",
                "windows_skipped",
            ),
            0,
        )
    )
    written = 0
    current_key: int | None = None
    buffer: list[BGLRecord] = []

    def flush() -> None:
        nonlocal written, buffer
        if current_key is None or len(buffer) < min_lines:
            stats["windows_skipped"] += 1 if buffer else 0
            buffer = []
            return
        if limit is not None and written >= limit:
            buffer = []
            return
        run_id = f"{written:06d}"
        start = buffer[0].epoch
        start_iso = datetime.fromtimestamp(start, tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        tags = Counter(r.label for r in buffer if r.is_alert)
        header = {
            "run_id": run_id,
            "soc": "BlueGene/L",
            "board": "LLNL",
            "test_suite": "bgl",
            "test_case": f"window_{start_iso}",
            "workload": "production",
            "window_s": str(window_s),
            "window_start": start_iso,
        }
        with open(out_logs / f"run_{run_id}.bgl.log", "w", encoding="utf-8") as fh:
            for k, v in header.items():
                fh.write(f"# {k}: {v}\n")
            fh.write("\n")
            for r in buffer:
                kv = f" | node={r.node} type={r.msg_type}"
                fh.write(
                    f"{_fmt_ts((r.epoch - start) * 1000)} {r.component}: {r.level}: {r.content}{kv}\n"
                )
        label = {
            "run_id": run_id,
            "anomalous": bool(tags),
            "failure_types": sorted(tags),
            "root_cause_id": tags.most_common(1)[0][0] if tags else None,
            "injected_patterns": [
                {"pattern_id": f"BGL_{t}", "failure_type": t, "root_cause_id": t, "count": n}
                for t, n in tags.most_common()
            ],
            "meta": {**header, "n_lines": len(buffer), "n_alert_lines": sum(tags.values())},
            "source": "loghub/BGL",
        }
        (out_labels / f"run_{run_id}.label.json").write_text(json.dumps(label, indent=2))
        written += 1
        stats["windows"] += 1
        stats["anomalous_windows"] += int(bool(tags))
        buffer = []

    with open(src, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            rec = parse_bgl_line(line)
            if rec is None:
                stats["unparsed_lines"] += 1
                continue
            stats["lines"] += 1
            stats["alert_lines"] += int(rec.is_alert)
            key = rec.epoch // window_s
            if current_key is not None and key != current_key:
                flush()
                if limit is not None and written >= limit:
                    break
            current_key = key
            buffer.append(rec)
    flush()
    return dict(stats)
